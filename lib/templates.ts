/** Worked out from the descriptor rather than stored per template, so adding a
 *  template files it in the right buckets without a second list to keep up. */
export function inCategory(t: Template, category: TemplateCategory): boolean {
  switch (category) {
    // Every template exports real text, but a sidebar is the one thing that can
    // make a parser read the page out of order — so a single column is what
    // "safe" means here.
    // A dark page is the other thing a parser can trip on — the text is real
    // either way, but "safe" here means nothing between it and the reader.
    case "ats":
      return t.sidebar === "none" && !t.edgeStrip && t.page === "light";
    case "classic":
      return t.font === "serif";
    case "modern":
      return t.font === "sans";
    // What people mean by minimal: one plain column, nothing decorative.
    case "minimal":
      return (
        t.photo === "none" &&
        t.sidebar === "none" &&
        !t.edgeStrip &&
        !t.headerBand &&
        t.page === "light" &&
        t.headingStyle !== "chip"
      );
    case "photo":
      return t.photo !== "none";
    case "two-column":
      return t.sidebar !== "none";
    case "compact":
      return t.density < 1;
    // Minimal without the purity test: one plain column and no photo, but a
    // banded heading or a tinted header is still allowed. This is what people
    // mean by "simple" — plain, not stripped.
    case "simple":
      return (
        t.photo === "none" &&
        t.sidebar === "none" &&
        !t.edgeStrip &&
        t.page === "light"
      );
    // The conservative register, typeface aside: nothing reversed out of a
    // chip, no proficiency meters, no numbered sections, no dark page, no
    // photo — the things that read as out of place in law, finance, medicine
    // and government.
    case "professional":
      return (
        t.page === "light" &&
        !t.edgeStrip &&
        !t.entryTitleChip &&
        t.photo === "none" &&
        t.headingStyle !== "chip" &&
        t.tags !== "dots" &&
        t.tags !== "bars" &&
        t.headingNumber === "none" &&
        t.sidebar !== "dark" &&
        !(t.headerBand && t.headerBandStyle === "accent")
      );
    // Business-formal with visible structure: a ruled or banded header, or
    // banded headings — the house-style look of an internal document.
    case "corporate":
      return (
        t.page === "light" &&
        t.headingNumber === "none" &&
        t.tags !== "dots" &&
        t.tags !== "bars" &&
        t.headingStyle !== "chip" &&
        !t.entryTitleChip &&
        (t.headerBand ||
          t.headerBox ||
          t.headerRule ||
          t.headingStyle === "band" ||
          t.headingStyle === "rules")
      );
    // Anything that makes a visual argument: a dark page, an edge strip,
    // reversed chips, numbered sections, meters, or a solid accent header.
    case "creative":
      return (
        t.page === "dark" ||
        t.edgeStrip ||
        t.headingStyle === "chip" ||
        t.entryTitleChip ||
        t.headingNumber !== "none" ||
        t.tags === "dots" ||
        t.tags === "bars" ||
        (t.headerBand && t.headerBandStyle === "accent")
      );
    case "one-column":
      return t.sidebar === "none";
    // What survives being rebuilt in Word: a single column of body text, no
    // rails, no meters, no reversed panels. Word can do the rest, badly.
    case "word":
      return (
        t.sidebar === "none" &&
        t.page === "light" &&
        !t.edgeStrip &&
        t.photo === "none" &&
        t.headingStyle !== "chip" &&
        t.tags !== "dots" &&
        t.tags !== "bars" &&
        !t.entryTitleChip
      );
    // Same idea, one step looser: Docs will place an image and hold a tint,
    // but a two-column layout there means a table, and tables are where a
    // Docs resume starts fighting you.
    case "google-docs":
      return (
        t.page === "light" &&
        !t.edgeStrip &&
        !t.photoBleed &&
        t.sidebar === "none" &&
        t.tags !== "dots" &&
        t.tags !== "bars" &&
        t.headingNumber === "none" &&
        t.headingStyle !== "chip"
      );
  }
}

export const templatesIn = (category: TemplateCategory): Template[] =>
  TEMPLATES.filter((t) => inCategory(t, category));

/** How many columns a tag style lays out in. Meter bars set their own — they
 *  need the width, and how much of it depends on where they land. */
export const tagColumns = (style: TagStyle): number =>
  style === "columns-4"
    ? 4
    : style === "columns-3"
      ? 3
      : style === "columns-2"
        ? 2
        : 1;
